use crate::config::AppConfigFile;
use crate::error::TemplateError;
use std::fs;
use std::path::Path;

pub const GENERATED_HEADER: &str = "// @generated by caf-template. DO NOT EDIT MANUALLY.\n\n";
pub const RUST_GENERATED_HEADER: &str = "// @generated by caf-template. DO NOT EDIT MANUALLY.\n\n";

pub struct CodegenOutput {
    pub path: String,
    pub content: String,
}

pub fn generate_all(config: &AppConfigFile) -> Vec<CodegenOutput> {
    let mut outputs = Vec::new();

    // 1. TS app.ts
    let window_width = config.window.as_ref().and_then(|w| w.width).unwrap_or(1200);
    let window_height = config.window.as_ref().and_then(|w| w.height).unwrap_or(800);
    let window_min_w = config
        .window
        .as_ref()
        .and_then(|w| w.min_width)
        .unwrap_or(900);
    let window_min_h = config
        .window
        .as_ref()
        .and_then(|w| w.min_height)
        .unwrap_or(600);
    let window_resizable = config
        .window
        .as_ref()
        .and_then(|w| w.resizable)
        .unwrap_or(true);

    let app_ts = format!(
        r#"{GENERATED_HEADER}export const APP_CONFIG = {{
  name: {:?},
  slug: {:?},
  code: {:?},
  identifier: {:?},
  accent: {:?},
  defaultLocale: {:?},
  locales: {:?},
  platforms: {:?},
  caframeworkVersion: {:?},
  window: {{
    width: {},
    height: {},
    minWidth: {},
    minHeight: {},
    resizable: {}
  }}
}} as const;
"#,
        config.app.name,
        config.app.slug,
        config.app.code,
        config.app.identifier,
        config.app.accent,
        config.app.default_locale,
        config.app.locales,
        config.app.platforms,
        config.app.caframework_version.as_deref().unwrap_or("0.1.0"),
        window_width,
        window_height,
        window_min_w,
        window_min_h,
        window_resizable,
    );
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/app.ts".into(),
        content: app_ts,
    });

    // 2. TS nav.ts (also write navItems.generated.ts for backwards compatibility)
    let mut nav_ts = format!(
        r#"{GENERATED_HEADER}export interface GeneratedNavItem {{
  key: string;
  labelEn: string;
  labelId: string;
  icon: string;
  accent: string;
  group: string;
  permission: string;
}}

export const GENERATED_NAV_ITEMS: GeneratedNavItem[] = [
"#
    );
    for m in &config.menus {
        let perm = m
            .permission
            .clone()
            .unwrap_or_else(|| format!("{}:view", m.key));
        let acc = m.accent.clone().unwrap_or_default();
        nav_ts.push_str(&format!(
            r#"  {{
    key: {:?},
    labelEn: {:?},
    labelId: {:?},
    icon: {:?},
    accent: {:?},
    group: {:?},
    permission: {:?}
  }},
"#,
            m.key, m.label_en, m.label_id, m.icon, acc, m.group, perm
        ));
    }
    nav_ts.push_str("];\n");
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/nav.ts".into(),
        content: nav_ts.clone(),
    });
    // For existing imports of navItems.generated.ts
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/navItems.generated.ts".into(),
        content: nav_ts,
    });

    // 3. TS menuLabels.ts
    let mut labels_ts = format!(
        r#"{GENERATED_HEADER}export const MENU_LABELS: Record<string, {{ en: string; id: string }}> = {{
"#
    );
    for m in &config.menus {
        labels_ts.push_str(&format!(
            "  {:?}: {{ en: {:?}, id: {:?} }},\n",
            m.key, m.label_en, m.label_id
        ));
    }
    labels_ts.push_str("};\n");
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/menuLabels.ts".into(),
        content: labels_ts,
    });

    // 4. TS permissions.ts
    let mut perms_ts = format!(
        r#"{GENERATED_HEADER}export interface RoleDefinition {{
  key: string;
  labelEn: string;
  labelId: string;
  permissions: readonly string[];
}}

export const SUPER_ROLE = {:?};
export const ALLOW_RUNTIME_ROLES = {};

export const ROLES: readonly RoleDefinition[] = [
"#,
        config.rbac.super_role,
        config.rbac.allow_runtime_roles.unwrap_or(true)
    );
    for r in &config.rbac.roles {
        perms_ts.push_str(&format!(
            r#"  {{
    key: {:?},
    labelEn: {:?},
    labelId: {:?},
    permissions: {:?}
  }},
"#,
            r.key, r.label_en, r.label_id, r.permissions
        ));
    }
    perms_ts.push_str("] as const;\n");
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/permissions.ts".into(),
        content: perms_ts,
    });

    // 5. TS brand.ts
    let brand_ts = format!(
        r#"{GENERATED_HEADER}export const BRAND_CONFIG = {{
  developer: {:?},
  company: {:?},
  website: {:?},
  email: {:?},
  phone: {:?},
  supportUrl: {:?},
  copyright: {:?},
  logo: {:?},
  showOnLockScreen: {}
}} as const;
"#,
        config.brand.developer,
        config.brand.company.as_deref().unwrap_or_default(),
        config.brand.website,
        config.brand.email,
        config.brand.phone,
        config
            .brand
            .support_url
            .as_deref()
            .unwrap_or(config.brand.website.as_str()),
        config.brand.copyright,
        config.brand.logo,
        config.brand.show_on_lock_screen.unwrap_or(true),
    );
    outputs.push(CodegenOutput {
        path: "frontend/src/lib/generated/brand.ts".into(),
        content: brand_ts,
    });

    // 6. Rust crates/caf-core/src/generated/prefix.rs
    let rust_prefix = format!(
        r#"{RUST_GENERATED_HEADER}pub const ERROR_PREFIX: &str = {:?};
pub const APP_NAME: &str = {:?};
pub const APP_SLUG: &str = {:?};
pub const APP_IDENTIFIER: &str = {:?};
"#,
        config.app.code, config.app.name, config.app.slug, config.app.identifier
    );
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/prefix.rs".into(),
        content: rust_prefix,
    });

    // 7. Rust crates/caf-core/src/generated/modules.rs
    let rust_modules = format!(
        r#"{RUST_GENERATED_HEADER}pub struct EnabledModules {{
    pub profiles: bool,
    pub ai: bool,
    pub pro: bool,
    pub feedback: bool,
    pub updater: bool,
    pub crash: bool,
    pub integrations: bool,
    pub scheduler: bool,
    pub support_page: bool,
}}

pub const ENABLED_MODULES: EnabledModules = EnabledModules {{
    profiles: {},
    ai: {},
    pro: {},
    feedback: {},
    updater: {},
    crash: {},
    integrations: {},
    scheduler: {},
    support_page: {},
}};
"#,
        config
            .modules
            .as_ref()
            .and_then(|m| m.profiles)
            .unwrap_or(true),
        config.modules.as_ref().and_then(|m| m.ai).unwrap_or(true),
        config.modules.as_ref().and_then(|m| m.pro).unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.feedback)
            .unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.updater)
            .unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.crash)
            .unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.integrations)
            .unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.scheduler)
            .unwrap_or(true),
        config
            .modules
            .as_ref()
            .and_then(|m| m.support_page)
            .unwrap_or(false),
    );
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/modules.rs".into(),
        content: rust_modules,
    });

    // 8. Rust crates/caf-core/src/generated/permissions.rs
    let mut rust_perms = format!(
        r#"{RUST_GENERATED_HEADER}pub const SUPER_ROLE: &str = {:?};
pub const ALLOW_RUNTIME_ROLES: bool = {};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RoleConfig {{
    pub key: &'static str,
    pub label_en: &'static str,
    pub label_id: &'static str,
    pub permissions: &'static [&'static str],
}}

pub const STATIC_ROLES: &[RoleConfig] = &[
"#,
        config.rbac.super_role,
        config.rbac.allow_runtime_roles.unwrap_or(true)
    );
    for r in &config.rbac.roles {
        let perms_items: Vec<String> = r.permissions.iter().map(|p| format!("{:?}", p)).collect();
        rust_perms.push_str(&format!(
            r#"    RoleConfig {{
        key: {:?},
        label_en: {:?},
        label_id: {:?},
        permissions: &[{}],
    }},
"#,
            r.key,
            r.label_en,
            r.label_id,
            perms_items.join(", ")
        ));
    }
    rust_perms.push_str("];\n");
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/permissions.rs".into(),
        content: rust_perms,
    });

    // 9. Rust crates/caf-core/src/generated/brand.rs
    let rust_brand = format!(
        r#"{RUST_GENERATED_HEADER}pub struct BrandInfo {{
    pub developer: &'static str,
    pub company: &'static str,
    pub website: &'static str,
    pub email: &'static str,
    pub phone: &'static str,
    pub support_url: &'static str,
    pub copyright: &'static str,
    pub logo: &'static str,
    pub show_on_lock_screen: bool,
}}

pub const BRAND: BrandInfo = BrandInfo {{
    developer: {:?},
    company: {:?},
    website: {:?},
    email: {:?},
    phone: {:?},
    support_url: {:?},
    copyright: {:?},
    logo: {:?},
    show_on_lock_screen: {},
}};
"#,
        config.brand.developer,
        config.brand.company.as_deref().unwrap_or_default(),
        config.brand.website,
        config.brand.email,
        config.brand.phone,
        config
            .brand
            .support_url
            .as_deref()
            .unwrap_or(config.brand.website.as_str()),
        config.brand.copyright,
        config.brand.logo,
        config.brand.show_on_lock_screen.unwrap_or(true)
    );
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/brand.rs".into(),
        content: rust_brand,
    });

    // 10. Rust crates/caf-core/src/generated/endpoints.rs
    let gcc_url = config
        .endpoints
        .as_ref()
        .and_then(|e| e.gcc_base_url.as_deref())
        .unwrap_or_default();
    let upd_url = config
        .endpoints
        .as_ref()
        .and_then(|e| e.updater_manifest_url.as_deref())
        .unwrap_or_default();
    let rust_endpoints = format!(
        r#"{RUST_GENERATED_HEADER}pub const GCC_BASE_URL: &str = {:?};
pub const UPDATER_MANIFEST_URL: &str = {:?};
"#,
        gcc_url, upd_url
    );
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/endpoints.rs".into(),
        content: rust_endpoints,
    });

    // 11. Rust crates/caf-core/src/generated/mod.rs
    let rust_mod = format!(
        r#"{RUST_GENERATED_HEADER}pub mod brand;
pub mod endpoints;
pub mod modules;
pub mod permissions;
pub mod prefix;
"#
    );
    outputs.push(CodegenOutput {
        path: "crates/caf-core/src/generated/mod.rs".into(),
        content: rust_mod,
    });

    for out in &mut outputs {
        if out.path.ends_with(".rs") {
            out.content = format_rust(&out.content);
        }
    }

    outputs
}

fn format_rust(code: &str) -> String {
    use std::io::Write;
    use std::process::{Command, Stdio};
    if let Ok(mut child) = Command::new("rustfmt")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
    {
        if let Some(mut stdin) = child.stdin.take() {
            let _ = stdin.write_all(code.as_bytes());
        }
        if let Ok(output) = child.wait_with_output()
            && output.status.success()
            && let Ok(formatted) = String::from_utf8(output.stdout)
        {
            return formatted;
        }
    }
    code.to_string()
}

pub fn run_codegen_on_root(
    root: &Path,
    config: &AppConfigFile,
    check: bool,
) -> Result<(), TemplateError> {
    let outputs = generate_all(config);

    for out in outputs {
        let target_path = root.join(&out.path);
        if check {
            if !target_path.exists() {
                return Err(TemplateError::Validation(
                    1,
                    format!(
                        "Codegen check failed: target file {:?} does not exist",
                        target_path
                    ),
                ));
            }
            let existing = fs::read_to_string(&target_path)?;
            if existing != out.content {
                return Err(TemplateError::Validation(
                    1,
                    format!(
                        "Codegen check failed: target file {:?} differs from generated content",
                        target_path
                    ),
                ));
            }
        } else {
            if let Some(parent) = target_path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(&target_path, out.content)?;
        }
    }

    Ok(())
}
